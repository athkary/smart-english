let lang = (() => {
  try { return localStorage.getItem("se.lang") || "ar"; } catch { return "ar"; }
})();

export function getLang() { return lang; }

export function setLang(next) {
  lang = next === "en" ? "en" : "ar";
  try { localStorage.setItem("se.lang", lang); } catch { /* private mode */ }
  applyDocumentLang();
}

export function applyDocumentLang() {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  document.title = t("app.name");
}

export function t(key, vars = {}) {
  let s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

/** Server errors carry message + message_ar. */
export function errorText(err) {
  if (err && err.body && err.body.error) return lang === "ar" ? err.body.error.message_ar : err.body.error.message;
  if (err && err.network) return t("error.network");
  return t("error.network");
}

